"""Write the example data files in data/ (all SYNTHETIC: generated from the models).

    python tools/make_example_data.py

* data/example_capstone_rig.csv -- the s07_capstone acceptance test, in exactly the
  format the sketch prints, simulated on the rig model with the sketch's default gains;
* data/thrust_template.csv -- the sheet students fill in during lab 3.

These let every notebook and the capstone analysis run before any hardware exists. They
are not measurements and are labelled as such inside the files.
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np

from bootcamp import attitude as att
from bootcamp import capstone
from bootcamp import easypid as ep
from bootcamp.logs import write_log

ROOT = Path(__file__).resolve().parents[1]


def capstone_example(path: Path) -> None:
    akp, aki, rkp, rki, rkd = 4.0, 0.0, 0.8, 0.6, 0.01  # s07_capstone defaults
    outer = ep.PIDController(akp, aki, 0.0, -150, 150)
    inner = ep.PIDController(rkp, rki, rkd, -200, 200)
    inner.setDerivativeFilter(ep.FILTER_EMA, 0.7)
    outer.begin()
    inner.begin()
    cf = att.ComplementaryFilter(0.0)
    rec = {"est": [], "rate_sp": []}

    def ctrl(t, sp, m, dt):
        cf.alpha = att.alpha_from_time_constant(0.5, dt)
        est = cf.update(m["gyro"], math.degrees(math.atan2(m["accel_x"], m["accel_z"])), dt)
        rate_sp = outer.update(sp, m["pot"], dt * 1000)  # src = pot, as the sketch default
        rec["est"].append(est)
        rec["rate_sp"].append(rate_sp)
        return inner.update(rate_sp, m["gyro"], dt * 1000)

    log = capstone.simulate_rig_test(ctrl, seed=7)
    k = slice(None, None, 4)  # the sketch logs at 50 Hz (every 4th 200 Hz loop)
    t_ms = np.round(5000 + 1000 * log.t[k])  # pretend the test started 5 s after boot
    write_log(
        path,
        {
            "t_ms": t_ms,
            "test_t": log.t[k],
            "sp": log.setpoint[k],
            "pot": log.pot[k],
            "est": np.array(rec["est"])[k],
            "rate_sp": np.array(rec["rate_sp"])[k],
            "rate": log.gyro[k],
            "u": log.u[k],
            "us1": np.round(log.us1[k]),
            "us2": np.round(log.us2[k]),
            "armed": np.ones(len(t_ms)),
        },
        comment=(
            "SYNTHETIC EXAMPLE - generated by tools/make_example_data.py from the rig model\n"
            "(bootcamp.rig, assumed parameters), not measured on hardware.\n"
            "Format: s07_capstone output after the 'test' command; gains 4/0 | 0.8/0.6/0.01."
        ),
    )


def thrust_template(path: Path) -> None:
    lines = [
        "# Lab 3 thrust curve: fill in the scale reading (grams) at each ESC pulse.",
        "# Beam level, motor-2 end resting on the tared scale, only motor 1 spinning",
        "# (s03_esc_bench, command 'sweep 1'). Read the scale ~3 s after each '# STEP' line.",
        "# Team:            Date:            Supply voltage (V):        Prop:",
        "us,grams",
    ]
    lines += [f"{us}," for us in range(1100, 1601, 50)]
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    capstone_example(ROOT / "data" / "example_capstone_rig.csv")
    thrust_template(ROOT / "data" / "thrust_template.csv")
    print("wrote data/example_capstone_rig.csv and data/thrust_template.csv")


if __name__ == "__main__":
    main()
